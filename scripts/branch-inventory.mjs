#!/usr/bin/env node
/**
 * Generate an inventory of every remote branch: last commit date, how far it
 * has diverged from the integration branch, and whether its work is already
 * contained in that branch.
 *
 * This reports; it does not delete. The repository currently carries ~70 remote
 * branches, several months old, and it is not possible to tell by looking which
 * are live — which is the precondition for cleaning them up safely. Deleting
 * someone else's branch is not a decision a script should make, so the output
 * is a document a human acts on.
 *
 * Usage:
 *   node scripts/branch-inventory.mjs [--integration main] [--out docs/branch-inventory.md]
 */
import process from "node:process";
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { classifyBranch, DEFAULT_MAX_MERGE_BASE_AGE_DAYS } from "./lib/branch-freshness.mjs";

function git(args) {
  return execFileSync("git", args, { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 }).trim();
}

function flag(name, fallback) {
  const index = process.argv.indexOf(`--${name}`);
  return index !== -1 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const integrationBranch = flag("integration", process.env.MORROW_INTEGRATION_BRANCH || "main");
const outPath = flag("out", "docs/branch-inventory.md");
const integrationRef = `origin/${integrationBranch}`;

const MS_PER_DAY = 24 * 60 * 60 * 1000;

const rows = [];
const raw = git(["for-each-ref", "--format=%(refname:short)%09%(committerdate:iso-strict)", "refs/remotes/origin"]);
const integrationTip = Date.parse(git(["show", "-s", "--format=%cI", integrationRef]));

for (const line of raw.split("\n")) {
  const [ref, committedIso] = line.split("\t");
  if (!ref || !committedIso) continue;
  if (ref === "origin/HEAD" || ref === integrationRef) continue;

  const branch = ref.replace(/^origin\//, "");
  let ahead = 0;
  let behind = 0;
  let mergeBaseIso = committedIso;
  try {
    const mergeBase = git(["merge-base", ref, integrationRef]);
    mergeBaseIso = git(["show", "-s", "--format=%cI", mergeBase]);
    ahead = Number(git(["rev-list", "--count", `${integrationRef}..${ref}`]));
    behind = Number(git(["rev-list", "--count", `${ref}..${integrationRef}`]));
  } catch {
    // Unrelated history (e.g. an imported orphan branch) — reported as-is.
  }
  const divergenceDays = Math.max(0, (integrationTip - Date.parse(mergeBaseIso)) / MS_PER_DAY);
  rows.push({
    branch,
    lastCommit: committedIso.slice(0, 10),
    ahead,
    behind,
    divergenceDays,
    status: classifyBranch({ merged: ahead === 0, ageDays: divergenceDays }),
  });
}

const order = { stale: 0, aging: 1, merged: 2, active: 3 };
rows.sort((a, b) => (order[a.status] - order[b.status]) || (b.divergenceDays - a.divergenceDays));

const count = (status) => rows.filter((r) => r.status === status).length;
const generatedAt = git(["show", "-s", "--format=%cI", integrationRef]).slice(0, 10);

const doc = `# Remote branch inventory

Generated by \`node scripts/branch-inventory.mjs\` against \`${integrationBranch}\` as of its
tip commit (${generatedAt}). Regenerate rather than hand-editing.

This is a decision aid, not an action. Nothing here is deleted automatically —
the point is that ${rows.length} remote branches currently exist and it is not
otherwise possible to tell which are live.

| Status | Count | Meaning |
|---|---|---|
| \`merged\` | ${count("merged")} | no commits outside \`${integrationBranch}\`; safe to delete |
| \`stale\` | ${count("stale")} | unmerged and diverged more than ${DEFAULT_MAX_MERGE_BASE_AGE_DAYS * 4} days of history; archive or delete deliberately |
| \`aging\` | ${count("aging")} | unmerged and past the ${DEFAULT_MAX_MERGE_BASE_AGE_DAYS}-day window; rebase onto \`${integrationBranch}\` or close |
| \`active\` | ${count("active")} | within the window |

\`ahead\` counts commits this branch has that \`${integrationBranch}\` does not.
\`divergence\` is how many days of integration history the branch has not absorbed —
the same measure \`scripts/check-branch-freshness.mjs\` enforces in CI.

| Branch | Status | Last commit | Ahead | Behind | Divergence (days) |
|---|---|---|---|---|---|
${rows.map((r) => `| \`${r.branch}\` | ${r.status} | ${r.lastCommit} | ${r.ahead} | ${r.behind} | ${r.divergenceDays.toFixed(1)} |`).join("\n")}
`;

await writeFile(outPath, doc, "utf8");
console.log(`branch-inventory: wrote ${rows.length} branches to ${outPath} (${count("merged")} merged, ${count("stale")} stale, ${count("aging")} aging, ${count("active")} active).`);
